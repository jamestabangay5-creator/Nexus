/**
 * Returns the list of barangays for a given municipality.
 * Falls back to Calapan City if the municipality is not found.
 */
export const getBarangaysForMunicipality = (municipality: string): string[] => {
  const match = ORIENTAL_MINDORO_BARANGAYS[municipality as OrientalMindoroMunicipality];
  if (match && match.length > 0) {
    return match;
  }
  return ORIENTAL_MINDORO_BARANGAYS['Calapan City'];
};

/**
 * Deduplicated, sorted list of all unique barangay names in Oriental Mindoro
 */
export const ALL_UNIQUE_ORIENTAL_MINDORO_BARANGAYS: string[] = Array.from(
  new Set(Object.values(ORIENTAL_MINDORO_BARANGAYS).flat())
).sort((a, b) => a.localeCompare(b));

/**
 * Helper to get unique barangays for a filter dropdown.
 * If municipality is 'ALL' or empty, returns all unique barangays across the province.
 */
export const getAllBarangaysForFilter = (selectedMunicipality?: string): string[] => {
  if (selectedMunicipality && selectedMunicipality !== 'ALL') {
    return getBarangaysForMunicipality(selectedMunicipality);
  }
  return ALL_UNIQUE_ORIENTAL_MINDORO_BARANGAYS;
};

